//! Unified JSON-RPC command dispatcher shared by the desktop Tauri shell
//! (`cpa-gui`) and the headless WebUI server (`ecpa-web`).

use crate::runtime::{AppHandle, RpcFuture, RpcResult};
use serde_json::Value;

type RpcHandler = fn(AppHandle, Value) -> RpcFuture;

/// Returns whether a command name is handled by the shared `ecpa-core` RPC layer.
pub fn is_known_command(command: &str) -> bool {
    lookup_local(command).is_some() || lookup_remote(command).is_some()
}

/// Dispatches a command respecting the active local vs. external remote CPA mode.
pub async fn dispatch(app: AppHandle, command: &str, args: Value) -> RpcResult {
    let remote = app
        .try_state::<crate::remote_cpa::RemoteCpaState>()
        .is_some_and(|state| state.uses_external_dispatch());
    let handler = if remote {
        match lookup_remote(command) {
            Some(handler) => handler,
            None if lookup_local(command).is_some() => {
                return Err(Value::String(format!(
                    "Built-in CPA operation unavailable for the selected external instance: {command}"
                )));
            }
            None => {
                return Err(Value::String(format!("Unknown command: {command}")));
            }
        }
    } else {
        match lookup_local(command) {
            Some(handler) => handler,
            None => {
                return Err(Value::String(format!("Unknown command: {command}")));
            }
        }
    };
    handler(app, args).await
}

